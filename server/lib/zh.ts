const MAP: Record<string, string> = {}
for (const [trad, simp] of PAIRS) {
  if (trad !== simp) MAP[trad] = simp
}

/** 把字串裡的常見繁體字換成簡體；沒涵蓋的字原樣保留。 */
export function toSimplified(text: string): string {
  let out = ''
  for (const ch of text) {
    out += MAP[ch] ?? ch
  }
  return out
}

/** ShareableProfile 的文字欄位全轉簡體（interests 比對種子用戶用）。 */
export function shareableToSimplified<T extends { intro: string; interests: string[]; chat_style: string; looking_for: string }>(p: T): T {
  return {
    ...p,
    intro: toSimplified(p.intro),
    interests: p.interests.map(toSimplified),
    chat_style: toSimplified(p.chat_style),
    looking_for: toSimplified(p.looking_for),
  }
}
